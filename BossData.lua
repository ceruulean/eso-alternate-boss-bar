function BossData:GetInstanceThresholds()
	local lang = GetCVar("Language.2")
	local zone = (GetZoneId(GetUnitZoneIndex("player")))
	local ZoneInstanceBosses = {}
	for _, entry in ipairs(BOSS_NAMES[zone]) do
		if thresholds[entry.id] then
			ZoneInstanceBosses[entry[lang]] = thresholds[entry.id]
		end
	end
	return ZoneInstanceBosses
end
